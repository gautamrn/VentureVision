from fastapi import APIRouter, Depends, HTTPException, Response

from app.middleware.rateLimiter import rateLimit
from app.schemas.models import SharedMemo, ShareCreated, ShareRequest, ShareView
from app.shares.sealing import verifySeal
from app.shares.store import ShareStore, getShareStore

router = APIRouter()

SHARES_PER_HOUR = 30


@router.post(
    "/shares",
    response_model=ShareCreated,
    status_code=201,
    dependencies=[Depends(rateLimit("shares", SHARES_PER_HOUR))],
)
async def createShare(request: ShareRequest, store: ShareStore = Depends(getShareStore)):
    for sealed in request.memos:
        if not verifySeal(sealed):
            raise HTTPException(
                status_code=403,
                detail="Only unmodified memos generated by this server can be shared. Run the analysis again to share it.",
            )
    memos = [
        SharedMemo(pitch=s.pitch, mode=s.mode, generated_at=s.seal.generated_at, memo=s.memo) for s in request.memos
    ]
    view = store.create(request.kind, memos, [s.seal.signature for s in request.memos])
    return ShareCreated(share_id=view.share_id, created_at=view.created_at)


@router.get("/shares/{shareId}", response_model=ShareView)
async def getShare(shareId: str, response: Response, store: ShareStore = Depends(getShareStore)):
    view = store.get(shareId)
    if view is None:
        raise HTTPException(status_code=404, detail="Shared memo not found.")
    response.headers["Cache-Control"] = "private, max-age=300"
    response.headers["X-Robots-Tag"] = "noindex, nofollow"
    return view

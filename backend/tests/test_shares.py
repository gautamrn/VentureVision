import json
import sqlite3

import pytest

from app.middleware.bodyLimit import MAX_BODY_BYTES
from app.schemas.models import MemoOutput
from app.shares.sealing import sealMemo
from tests.fakes import SAMPLE_PITCH, competitorDraft, critique, memoSynthesis, researchPlan

QUERY = "dog walking app competitors"


@pytest.fixture
def client(liveServer):
    return liveServer


def completedRun(client, fakeOpenAI, pitchScore: int = 64) -> dict:
    fakeOpenAI.script("ResearchPlan", researchPlan([QUERY]))
    fakeOpenAI.script("CritiqueResult", critique(0.9, True))
    fakeOpenAI.script(
        "MemoSynthesis",
        memoSynthesis(pitchScore=pitchScore, competitors=[competitorDraft("Rover", 1, f"Evidence about {QUERY}.")]),
    )
    with client.stream("POST", "/analyze/stream", json={"pitch": SAMPLE_PITCH}) as response:
        name = None
        for line in response.iter_lines():
            if line.startswith("event: "):
                name = line[7:].strip()
            elif line.startswith("data: ") and name == "citation_audit":
                data = json.loads(line[6:])
                return {"pitch": SAMPLE_PITCH, "mode": "market_scan", "memo": data["memo"], "seal": data["seal"]}
    raise AssertionError("run produced no citation_audit event")


def share(client, kind: str, memos: list[dict]):
    return client.post("/shares", json={"kind": kind, "memos": memos})


def testSharedMemoKeepsCitationsGroundednessAndRunDate(client, fakeOpenAI, fakeTavily):
    sealed = completedRun(client, fakeOpenAI)

    created = share(client, "memo", [sealed])
    assert created.status_code == 201
    shareId = created.json()["share_id"]
    assert len(shareId) == 22, "128 random bits, URL-safe"

    response = client.get(f"/shares/{shareId}")
    assert response.status_code == 200
    assert response.headers["x-robots-tag"] == "noindex, nofollow"
    view = response.json()
    assert view["kind"] == "memo"
    shared = view["memos"][0]
    assert shared["pitch"] == SAMPLE_PITCH
    assert shared["generated_at"].startswith(sealed["seal"]["generated_at"][:19])
    assert shared["memo"]["groundedness"] == sealed["memo"]["groundedness"]
    assert shared["memo"]["market_matrix"][0]["citation"]["quote"] == f"Evidence about {QUERY}."
    assert shared["memo"]["telemetry"]["total_cost_usd"] > 0


def testSharingTheSameMemoTwiceReturnsTheSameLink(client, fakeOpenAI, fakeTavily):
    sealed = completedRun(client, fakeOpenAI)

    first = share(client, "memo", [sealed]).json()["share_id"]
    second = share(client, "memo", [sealed]).json()["share_id"]

    assert first == second


@pytest.mark.parametrize(
    "tamper",
    [
        lambda s: s["memo"].update(pitch_score=99),
        lambda s: s.update(pitch="Totally different pitch text that the server never analyzed."),
        lambda s: s.update(mode="pitch_lab"),
        lambda s: s["seal"].update(generated_at="2020-01-01T00:00:00Z"),
        lambda s: s["memo"]["market_matrix"][0]["citation"].update(quote="A quote the source never said."),
    ],
    ids=["score", "pitch", "mode", "date", "citation"],
)
def testModifiedMemosCannotBeShared(client, fakeOpenAI, fakeTavily, tamper):
    sealed = completedRun(client, fakeOpenAI)
    tamper(sealed)

    response = share(client, "memo", [sealed])

    assert response.status_code == 403
    assert "generated by this server" in response.json()["detail"]


def testSealSurvivesJavaScriptNumberFormatting(client, fakeOpenAI, fakeTavily):
    sealed = completedRun(client, fakeOpenAI)
    memo = MemoOutput.model_validate({**sealed["memo"], "confidence_score": 1.0})
    seal = sealMemo(sealed["pitch"], sealed["mode"], memo)
    browserCopy = {**sealed, "memo": memo.model_dump(mode="json"), "seal": seal.model_dump(mode="json")}
    # JSON.stringify(1.0) is "1"; Pydantic restores the float before the seal is checked.
    browserCopy["memo"]["confidence_score"] = 1

    assert share(client, "memo", [browserCopy]).status_code == 201


def testCompareShareHoldsBothMemosInOrder(client, fakeOpenAI, fakeTavily):
    left = completedRun(client, fakeOpenAI, pitchScore=40)
    right = completedRun(client, fakeOpenAI, pitchScore=80)

    assert share(client, "compare", [left]).status_code == 422
    shareId = share(client, "compare", [left, right]).json()["share_id"]

    view = client.get(f"/shares/{shareId}").json()
    assert view["kind"] == "compare"
    assert [m["memo"]["pitch_score"] for m in view["memos"]] == [40, 80]


def testUnknownAndMalformedShareIdsAre404(client):
    assert client.get("/shares/AAAAAAAAAAAAAAAAAAAAAA").status_code == 404
    assert client.get("/shares/not-a-share").status_code == 404
    assert client.get("/shares/' OR 1=1 --").status_code == 404


def testOversizedShareBodyIsRejectedBeforeParsing(client):
    response = client.post(
        "/shares", content=b"x" * (MAX_BODY_BYTES + 1), headers={"Content-Type": "application/json"}
    )
    assert response.status_code == 413


def testViewingAShareStoresNothingAboutTheVisitor(client, fakeOpenAI, fakeTavily, shareStore, tmp_path):
    shareId = share(client, "memo", [completedRun(client, fakeOpenAI)]).json()["share_id"]
    dbPath = tmp_path / "shares.sqlite3"
    before = dbPath.read_bytes()

    for _ in range(3):
        client.get(f"/shares/{shareId}", headers={"User-Agent": "visitor", "X-Forwarded-For": "203.0.113.9"})

    assert dbPath.read_bytes() == before
    with sqlite3.connect(dbPath) as db:
        columns = {row[1] for row in db.execute("PRAGMA table_info(shares)")}
        tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
    assert columns == {"share_id", "content_hash", "kind", "created_at", "memos"}
    assert tables == {"shares"}
